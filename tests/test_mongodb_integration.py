def test_explain_operations_return_execution_statistics(integration_api):
    api, db = integration_api
    db.employees.insert_one(employee_payload("EMP93001"))
    db.attendance_logs.insert_one(
        attendance_doc("EMP93001", "2026-07-06", "PRESENT", punch_in=local_time(6, 9, 30), punch_out=local_time(6, 18, 30), work_hours=9.0)
    )
    requests = [
        "/admin/explain/attendance_list?date_from=2026-07-01&date_to=2026-07-31",
        "/admin/explain/employee_monthly?emp_code=EMP93001&month=2026-07",
        "/admin/explain/department_summary?month=2026-07",
        "/admin/explain/late_leaderboard?month=2026-07",
        "/admin/explain/department_trend?department=Engineering&from=2026-07-06&to=2026-07-08",
    ]
    for path in requests:
        response = api.get(path)
        assert response.status_code == 200, (path, response.text)
        payload = response.json()
        assert payload["explain"]
        assert payload["collection"] in {"attendance_logs", "employees"}
        # The exact nesting differs between classic and slot-based MongoDB explain output.
        assert "executionStats" in str(payload["explain"]) or "executionTimeMillis" in str(payload["explain"])

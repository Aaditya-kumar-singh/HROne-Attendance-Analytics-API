"""Opt-in integration tests against a uniquely named, disposable MongoDB database.

Run only when explicitly enabled:
    $env:HRONE_RUN_INTEGRATION = "1"
    python -m pytest -q tests/test_mongodb_integration.py

The fixture never uses MONGO_DB as its test database and drops only the database
whose name it generated. It does not seed, clear, or drop any existing database.
"""
from __future__ import annotations

import os
import uuid
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timedelta, timezone

import pytest
from fastapi.testclient import TestClient

from app import main


IST = timezone(timedelta(hours=5, minutes=30))
UTC = timezone.utc
RUN_INTEGRATION = os.getenv("HRONE_RUN_INTEGRATION") == "1"


def epoch_ms(local: datetime) -> int:
    return int(local.astimezone(UTC).replace(microsecond=0).timestamp() * 1000)


def local_time(day: int, hour: int, minute: int = 0, second: int = 0) -> datetime:
    return datetime(2026, 7, day, hour, minute, second, tzinfo=IST)


def employee_payload(code: str, *, department: str = "Engineering", joined_on: str = "2026-07-01") -> dict:
    return {
        "emp_code": code,
        "name": f"Employee {code}",
        "email": f"{code.lower()}@example.test",
        "department": department,
        "shift_start": "09:30",
        "shift_end": "18:30",
        "joined_on": joined_on,
    }


def attendance_doc(
    code: str,
    day: str,
    status: str,
    *,
    punch_in: datetime | None = None,
    punch_out: datetime | None = None,
    work_hours: float | None = None,
    late_minutes: int = 0,
    overtime_minutes: int = 0,
    half_day: bool = False,
) -> dict:
    return {
        "emp_code": code,
        "date": day,
        "status": status,
        "punch_in": punch_in.astimezone(UTC).replace(microsecond=0) if punch_in else None,
        "punch_out": punch_out.astimezone(UTC).replace(microsecond=0) if punch_out else None,
        "work_hours": work_hours,
        "late_minutes": late_minutes,
        "overtime_minutes": overtime_minutes,
        "half_day": half_day,
        "history": [],
    }


@pytest.fixture
def integration_api(monkeypatch):
    if not RUN_INTEGRATION:
        pytest.skip("Set HRONE_RUN_INTEGRATION=1 to enable disposable MongoDB integration tests.")

    # Use the application's configured MongoClient, but NEVER its configured DB.
    # A UUID prevents collision between runs; the prefix makes ownership explicit.
    original_db_name = main.db.name
    test_db_name = f"hrone_it_{uuid.uuid4().hex[:16]}"
    if test_db_name == original_db_name or not test_db_name.startswith("hrone_it_"):
        pytest.fail("Safety guard refused a non-disposable integration database name.")

    test_db = main.client[test_db_name]
    monkeypatch.setattr(main, "db", test_db)
    try:
        with TestClient(main.app) as client:
            # Ensure startup created expected collections/indexes in this disposable DB.
            assert set(test_db.list_collection_names()) >= {"employees", "attendance_logs"}
            yield client, test_db
    finally:
        # Drop only the database name generated by this fixture, never MONGO_DB.
        assert test_db_name.startswith("hrone_it_") and test_db_name != original_db_name
        main.client.drop_database(test_db_name)


def test_health_and_complete_employee_attendance_lifecycle(integration_api):
    api, db = integration_api
    assert api.get("/health").status_code == 200

    payload = employee_payload("EMP91001")
    created = api.post("/employees", json=payload)
    assert created.status_code == 201
    assert created.json()["emp_code"] == "EMP91001"
    assert "id" not in created.json() and "_id" not in created.json()

    duplicate = api.post("/employees", json=payload)
    assert duplicate.status_code == 409
    assert api.get("/employees?department=Engineering&page=1&page_size=10").json()["total"] == 1

    punched_in = api.post(
        "/attendance/punch-in",
        json={"emp_code": "EMP91001", "punched_at": epoch_ms(local_time(6, 9, 30))},
    )
    assert punched_in.status_code == 201
    assert punched_in.json()["date"] == "2026-07-06"
    assert punched_in.json()["punch_in"] == epoch_ms(local_time(6, 9, 30))
    assert punched_in.json()["history"] == []

    duplicate_punch = api.post(
        "/attendance/punch-in",
        json={"emp_code": "EMP91001", "punched_at": epoch_ms(local_time(6, 9, 31))},
    )
    assert duplicate_punch.status_code == 409

    listed = api.get("/attendance?emp_code=EMP91001&date_from=2026-07-06&date_to=2026-07-06")
    assert listed.status_code == 200
    assert listed.json()["total"] == 1
    assert listed.json()["items"][0]["emp_code"] == "EMP91001"

    punched_out = api.post(
        "/attendance/punch-out",
        json={"emp_code": "EMP91001", "punched_at": epoch_ms(local_time(6, 19, 0))},
    )
    assert punched_out.status_code == 200
    record = punched_out.json()
    assert record["work_hours"] == 9.5
    assert record["overtime_minutes"] == 30
    assert record["late_minutes"] == 0
    assert record["half_day"] is False
    assert record["history"] == []
    assert "id" not in record and "_id" not in record

    second_punch_out = api.post(
        "/attendance/punch-out",
        json={"emp_code": "EMP91001", "punched_at": epoch_ms(local_time(6, 19, 1))},
    )
    assert second_punch_out.status_code == 409

    stored = db.attendance_logs.find_one({"emp_code": "EMP91001", "date": "2026-07-06"})
    assert stored is not None
    assert stored["punch_in"].tzinfo is None  # PyMongo's default BSON UTC decoding
    assert stored["work_hours"] == 9.5
    assert stored["overtime_minutes"] == 30


def test_regularization_history_validation_and_serialization(integration_api):
    api, db = integration_api
    assert api.post("/employees", json=employee_payload("EMP91002")).status_code == 201
    start = epoch_ms(local_time(7, 9, 30))
    end = epoch_ms(local_time(7, 18, 30))
    assert api.post("/attendance/punch-in", json={"emp_code": "EMP91002", "punched_at": start}).status_code == 201
    assert api.post("/attendance/punch-out", json={"emp_code": "EMP91002", "punched_at": end}).status_code == 200

    patch = api.patch(
        "/attendance/EMP91002/2026-07-07",
        json={"status": "WFH", "reason": "Approved remote work", "regularized_by": "supervisor"},
    )
    assert patch.status_code == 200
    body = patch.json()
    assert body["status"] == "WFH"
    assert len(body["history"]) == 1
    event = body["history"][0]
    assert event["by"] == "supervisor"
    assert event["reason"] == "Approved remote work"
    assert set(event["changes"]) == {"status"}
    assert event["changes"]["status"] == {"from": "PRESENT", "to": "WFH"}
    assert isinstance(event["at"], int)
    assert "id" not in body and "_id" not in body

    no_op = api.patch(
        "/attendance/EMP91002/2026-07-07",
        json={"status": "WFH", "reason": "No actual change", "regularized_by": "supervisor"},
    )
    assert no_op.status_code == 422
    null_timestamp = api.patch(
        "/attendance/EMP91002/2026-07-07",
        json={"punch_in": None, "reason": "Bad null timestamp", "regularized_by": "supervisor"},
    )
    assert null_timestamp.status_code == 422
    null_status = api.patch(
        "/attendance/EMP91002/2026-07-07",
        json={"status": None, "reason": "Bad null status", "regularized_by": "supervisor"},
    )
    assert null_status.status_code == 422
    invalid_state = api.patch(
        "/attendance/EMP91002/2026-07-07",
        json={"status": "LEAVE", "punch_out": end, "reason": "Invalid leave edit", "regularized_by": "supervisor"},
    )
    assert invalid_state.status_code == 422

    stored = db.attendance_logs.find_one({"emp_code": "EMP91002", "date": "2026-07-07"})
    assert len(stored["history"]) == 1
    assert stored["history"][0]["changes"] == {"status": {"from": "PRESENT", "to": "WFH"}}


def test_concurrent_create_punch_in_punch_out_and_regularization(integration_api):
    api, db = integration_api
    duplicate_payload = employee_payload("EMP91003")

    def create_once():
        return api.post("/employees", json=duplicate_payload).status_code

    with ThreadPoolExecutor(max_workers=8) as pool:
        create_results = list(pool.map(lambda _: create_once(), range(8)))
    assert create_results.count(201) == 1
    assert create_results.count(409) == 7
    assert db.employees.count_documents({"emp_code": "EMP91003"}) == 1

    punch_in_payload = {"emp_code": "EMP91003", "punched_at": epoch_ms(local_time(8, 9, 30))}
    with ThreadPoolExecutor(max_workers=8) as pool:
        punch_in_results = list(pool.map(lambda _: api.post("/attendance/punch-in", json=punch_in_payload).status_code, range(8)))
    assert punch_in_results.count(201) == 1
    assert punch_in_results.count(409) == 7
    assert db.attendance_logs.count_documents({"emp_code": "EMP91003", "date": "2026-07-08"}) == 1

    punch_out_payload = {"emp_code": "EMP91003", "punched_at": epoch_ms(local_time(8, 18, 30))}
    with ThreadPoolExecutor(max_workers=8) as pool:
        punch_out_results = list(pool.map(lambda _: api.post("/attendance/punch-out", json=punch_out_payload).status_code, range(8)))
    assert punch_out_results.count(200) == 1
    assert punch_out_results.count(409) == 7

    def regularize(status: str):
        return api.patch(
            "/attendance/EMP91003/2026-07-08",
            json={"status": status, "reason": f"Concurrency test {status}", "regularized_by": "parallel-test"},
        )

    with ThreadPoolExecutor(max_workers=2) as pool:
        responses = list(pool.map(regularize, ["WFH", "ON_DUTY"]))
    statuses = [response.status_code for response in responses]
    assert statuses in ([200, 409], [409, 200], [200, 200])
    successful_edits = statuses.count(200)
    stored = db.attendance_logs.find_one({"emp_code": "EMP91003", "date": "2026-07-08"})
    # If requests serialize, both may succeed; if they race on the same version,
    # one may conflict. Every successful edit must have its own retained history event.
    assert len(stored["history"]) == successful_edits
    assert all(set(event["changes"]) == {"status"} for event in stored["history"])


